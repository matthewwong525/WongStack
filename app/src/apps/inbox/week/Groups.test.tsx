// @vitest-environment jsdom
import { act, fireEvent, screen, waitFor, within } from '@testing-library/react'
import { expect, it } from 'vitest'
import { blur, button, calls, fake, hold, key, open, press, settle, task, titles, type } from './week.test.kit'

const notice = () => screen.queryByRole('alert')?.textContent ?? null
const columns = () => [...screen.getByTestId('backlog-grid').querySelectorAll('h3')].map(heading => heading.textContent)
const nameBox = () => screen.getByLabelText<HTMLInputElement>('Subgroup name')
const manage = async (name: string, item: string) => {
  await press(button(`Manage ${name}`))
  await press(screen.getByRole('menuitem', { name: item }))
}
const home = () => fake.groups.push({ id: 'group_1', name: 'Home', position: 2000, isDefault: false })

it('adds a subgroup by name, refusing a name in use, and stops on Escape or an empty name', async () => {
  await open()
  expect(within(screen.getByTestId('backlog-grid')).getByText('default')).toBeTruthy()
  await press(button('New subgroup'))
  expect(document.activeElement).toBe(nameBox())
  await key(nameBox(), 'Escape')
  expect(screen.queryByLabelText('Subgroup name')).toBeNull()
  await press(button('New subgroup'))
  await key(nameBox(), 'Enter')
  expect(screen.queryByLabelText('Subgroup name')).toBeNull()
  await press(button('New subgroup'))
  await type(nameBox(), ' other ')
  await key(nameBox(), 'Enter')
  expect(screen.getByRole('alert').textContent).toBe('That subgroup already exists.')
  expect(nameBox().getAttribute('aria-invalid')).toBe('true')
  await type(nameBox(), 'Home')
  expect(screen.queryByRole('alert')).toBeNull()
  await key(nameBox(), 'a')
  await blur(nameBox())
  await settle()
  expect(columns()).toEqual(['Other', 'Home'])
  expect(calls('POST group')[0].body).toEqual({ name: 'Home' })
  expect(fake.groups.map(group => group.id)).toEqual(['backlog_other', 'group_1'])
})

it('files tasks and moves in a subgroup the app is still making, once it has its id', async () => {
  task('Plan', { slot: 'backlog' })
  await open()
  const gate = hold('POST group')
  await press(button('New subgroup'))
  await type(nameBox(), 'Home')
  await key(nameBox(), 'Enter')
  const add = screen.getByLabelText('Add task to Home')
  await type(add, 'Paint')
  await key(add, 'Enter')
  await manage('Home', 'Move earlier')
  expect(columns()).toEqual(['Home', 'Other'])
  expect(calls('POST task')).toHaveLength(0)
  await gate.release()
  await settle()
  expect(calls('POST task')[0].body).toEqual({ title: 'Paint', week: '2026-10-26', slot: 'backlog', backlogGroupId: 'group_1' })
  expect(calls('POST group-move')[0].body).toEqual({ id: 'group_1', index: 0 })
  expect(titles('backlog-group-group_1')).toEqual(['Paint'])
  expect(titles('day-backlog')).toEqual(['Plan'])
})

it('says when a subgroup did not save, and sends no task filed in it', async () => {
  await open()
  const gate = hold('POST group')
  fake.fail = 'POST group'
  await press(button('New subgroup'))
  await type(nameBox(), 'Home')
  await key(nameBox(), 'Enter')
  const add = screen.getByLabelText('Add task to Home')
  await type(add, 'Paint')
  await key(add, 'Enter')
  await gate.release()
  await settle()
  expect(notice()).toMatch(/did not save/)
  expect(calls('POST task')).toHaveLength(0)
})

it('renames a subgroup, and keeps the name when it is the same, in use, or did not save', async () => {
  home()
  await open()
  await press(button('Manage Other'))
  expect(screen.queryByRole('menuitem', { name: 'Rename' })).toBeNull()
  expect(screen.queryByRole('menuitem', { name: 'Delete subgroup' })).toBeNull()
  expect(screen.getByRole('menuitem', { name: 'Move earlier' }).getAttribute('aria-disabled')).toBe('true')
  await key(screen.getByRole('menu'), 'Escape')
  await manage('Home', 'Rename')
  expect(nameBox().value).toBe('Home')
  await key(nameBox(), 'Enter')
  expect(calls('PATCH group')).toHaveLength(0)
  await manage('Home', 'Rename')
  await type(nameBox(), 'OTHER')
  await key(nameBox(), 'Enter')
  expect(screen.getByRole('alert').textContent).toBe('That subgroup already exists.')
  await key(nameBox(), 'Escape')
  await manage('Home', 'Rename')
  await type(nameBox(), 'House')
  await key(nameBox(), 'Enter')
  await settle()
  expect(columns()).toEqual(['Other', 'House'])
  expect(calls('PATCH group')[0].body).toEqual({ id: 'group_1', name: 'House' })
  fake.fail = 'PATCH group'
  await manage('House', 'Rename')
  await type(nameBox(), 'Flat')
  await key(nameBox(), 'Enter')
  await settle()
  expect(columns()).toEqual(['Other', 'House'])
  expect(notice()).toContain('That subgroup rename did not save.')
})

it('moves a subgroup earlier and later, and back when the move did not save', async () => {
  home()
  await open()
  expect(screen.queryByRole('menuitem')).toBeNull()
  await press(button('Manage Home'))
  expect(screen.getByRole('menuitem', { name: 'Move later' }).getAttribute('aria-disabled')).toBe('true')
  await press(screen.getByRole('menuitem', { name: 'Move earlier' }))
  await settle()
  expect(columns()).toEqual(['Home', 'Other'])
  fake.fail = 'POST group-move'
  await manage('Home', 'Move later')
  await settle()
  expect(columns()).toEqual(['Home', 'Other'])
  expect(notice()).toContain('That subgroup move did not save.')
  // A press on the grip may start a drag, so only the tap after it opens the menu.
  const grip = button('Manage Home')
  await act(async () => {
    fireEvent.pointerDown(grip, { button: 0 })
    fireEvent.pointerUp(grip)
    fireEvent.pointerDown(grip, { button: 2 })
    fireEvent.pointerCancel(grip)
    fireEvent.contextMenu(grip)
  })
  expect(screen.queryByRole('menu')).toBeNull()
})

it('deletes a subgroup after asking, moving its tasks and categories to Other', async () => {
  home()
  fake.groups.push({ id: 'group_2', name: 'Work', position: 3000, isDefault: false })
  fake.groups.push({ id: 'group_3', name: 'Play', position: 4000, isDefault: false })
  task('Paint', { slot: 'backlog', backlogGroupId: 'group_1' })
  task('Fix', { slot: 'backlog', backlogGroupId: 'group_1' })
  task('Mail', { slot: 'backlog', backlogGroupId: 'group_2' })
  task('Read', { backlogGroupId: 'group_1' })
  await open()
  await manage('Play', 'Delete subgroup')
  expect(screen.getByRole('alertdialog').textContent).toContain('The empty subgroup will be removed.')
  await press(button('Cancel'))
  await waitFor(() => expect(document.activeElement).toBe(button('Manage Play')))
  await manage('Work', 'Delete subgroup')
  expect(screen.getByRole('alertdialog').textContent).toContain('1 task will move to Other.')
  await press(button('Cancel'))
  await manage('Home', 'Delete subgroup')
  expect(screen.getByRole('alertdialog').textContent).toContain('2 tasks will move to Other.')
  await press(within(screen.getByRole('alertdialog')).getByRole('button', { name: 'Delete subgroup' }))
  await settle()
  expect(columns()).toEqual(['Other', 'Work', 'Play'])
  expect(titles('day-backlog')).toEqual(['Paint', 'Fix'])
  expect(calls('DELETE group')[0].route).toBe('group')
  fake.fail = 'DELETE group'
  await manage('Play', 'Delete subgroup')
  await press(within(screen.getByRole('alertdialog')).getByRole('button', { name: 'Delete subgroup' }))
  await settle()
  expect(columns()).toEqual(['Other', 'Work', 'Play'])
  expect(notice()).toContain('That subgroup was not deleted.')
})

it('opens no dialog focus return when the control that opened it is gone', async () => {
  home()
  task('Paint', { slot: 'backlog', backlogGroupId: 'group_1' })
  await open()
  await manage('Home', 'Delete subgroup')
  await press(within(screen.getByRole('alertdialog')).getByRole('button', { name: 'Delete subgroup' }))
  await settle()
  expect(screen.queryByLabelText('Manage Home')).toBeNull()
  expect(document.activeElement).toBe(document.body)
})
