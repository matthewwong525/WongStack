// @vitest-environment jsdom
import { act, fireEvent, screen, waitFor, within } from '@testing-library/react'
import { expect, it } from 'vitest'
import { line } from '../line.test.kit'
import { blur, box, button, calls, DAY, fake, hold, key, menu, open, press, row, settle, task, titles, type, WEEK } from './week.test.kit'

const notice = () => screen.queryByRole('alert')?.textContent ?? null
const lastBody = (route: string) => calls(route).at(-1)!.body
const caret = (element: HTMLTextAreaElement, at: number) => element.setSelectionRange(at, at)

it('checks a task off and back, and starts and stops sized work', async () => {
  task('Read (1)')
  await open()
  await press(screen.getByRole('checkbox', { name: 'Read' }))
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_1', status: 'done' })
  expect(box('Read').className).toContain('line-through')
  expect(screen.getByLabelText('Estimate for Read').textContent).toBe('1h')
  await press(screen.getByRole('checkbox', { name: 'Read' }))
  await press(button('Start Read'))
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_1', status: 'in_progress' })
  expect(screen.getByRole('checkbox', { name: 'Read, in progress' })).toBeTruthy()
  await press(button('Stop Read'))
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_1', status: 'open' })
  fake.fail = 'PATCH task'
  await press(button('Start Read'))
  await settle()
  expect(notice()).toContain('That change did not save.')
  expect(button('Start Read')).toBeTruthy()
})

