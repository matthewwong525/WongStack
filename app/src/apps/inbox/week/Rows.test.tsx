it('moves a task to next week, to the backlog, or to another category from its menu', async () => {
  task('Read', { backlogGroupId: 'group_1' })
  task('Write', { slot: 'thu' })
  task('Fix')
  fake.groups.push({ id: 'group_1', name: 'Home', position: 2000, isDefault: false })
  await open()
  // A press opens nothing: the grip may be starting a drag. The tap after it opens the menu.
  const grip = button('Task actions for Fix')
  await act(async () => {
    fireEvent.pointerDown(grip, { button: 0 })
    fireEvent.pointerUp(grip)
    fireEvent.pointerDown(grip, { button: 2 })
    fireEvent.pointerCancel(grip)
    fireEvent.contextMenu(grip)
  })
  expect(screen.queryByRole('menu')).toBeNull()
  await press(grip)
  await key(screen.getByRole('menuitem', { name: 'Category' }), 'ArrowRight')
  expect(screen.getAllByRole('menuitem').map(item => item.textContent)).toContain('Other')
  await press(screen.getByRole('menuitem', { name: 'Home' }))
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_3', backlogGroupId: 'group_1' })
  await menu('Fix', 'Home ✓', 'Category')
  fake.fail = 'PATCH task'
  await menu('Fix', 'Other', 'Category')
  await settle()
  expect(notice()).toContain('That category did not save.')
  await menu('Read', 'Move to backlog')
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_1', slot: 'backlog', backlogGroupId: 'group_1', index: 0 })
  expect(titles('backlog-group-group_1')).toEqual(['Read'])
  await menu('Write', 'Move to backlog')
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_2', slot: 'backlog', backlogGroupId: 'backlog_other', index: 0 })
  await menu('Fix', 'Move to next week')
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_3', week: '2026-11-02', slot: 'wed' })
  expect(screen.queryByLabelText('Edit Fix')).toBeNull()
  // A backlog task has no category and no next week.
  await press(button('Task actions for Read'))
  expect(screen.queryByRole('menuitem', { name: 'Category' })).toBeNull()
  expect(screen.queryByRole('menuitem', { name: 'Move to next week' })).toBeNull()
})

it('moves a task to a chosen date: another week, another day, or nowhere for the same day', async () => {
  task('Read')
  task('Write')
  task('Plan', { slot: 'backlog' })
  await open()
  const dialog = async (title: string) => {
    await menu(title, 'Move to date…')
    return screen.getByLabelText<HTMLInputElement>('Date')
  }
  expect((await dialog('Plan')).value).toBe(DAY)
  await press(button('Cancel'))
  expect(screen.queryByRole('dialog')).toBeNull()
  await waitFor(() => expect(document.activeElement).toBe(button('Task actions for Plan')))
  expect((await dialog('Read')).value).toBe(DAY)
  await press(button('Move task'))
  expect(calls('PATCH task')).toHaveLength(0)
  await type(await dialog('Read'), '')
  await act(async () => { fireEvent.submit(screen.getByLabelText('Date').closest('form')!) })
  expect(calls('PATCH task')).toHaveLength(0)
  await type(await dialog('Read'), '2026-10-30')
  await press(button('Move task'))
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_1', week: WEEK, slot: 'fri', index: 0 })
  expect(titles('day-fri')).toEqual(['Read'])
  await type(await dialog('Write'), '2026-11-09')
  await press(button('Move task'))
  await settle()
  expect(lastBody('PATCH task')).toEqual({ id: 'task_2', week: '2026-11-09', slot: 'mon' })
  expect(screen.queryByLabelText('Edit Write')).toBeNull()
  await dialog('Read')
  await key(screen.getByRole('dialog'), 'Escape')
  expect(screen.queryByRole('dialog')).toBeNull()
})

