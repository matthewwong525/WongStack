it('cuts a line at the caret with Enter, and stores the new line once it has text', async () => {
  task('Read book (1)')
  task('Write')
  await open()
  const read = box('Read book')
  caret(read, 4)
  await key(read, 'Enter')
  await settle()
  expect(titles('day-wed')).toEqual(['Read', 'book', 'Write'])
  expect(calls('PATCH task').map(call => call.body)).toEqual([{ id: 'task_1', title: 'Read (1)' }])
  expect(calls('POST task').map(call => call.body)).toEqual([{ title: 'book', week: WEEK, slot: 'wed' }])
  expect(document.activeElement).toBe(box('book'))
  expect(box('book').selectionStart).toBe(0)
  // At the end, Enter opens an empty line; it is stored when it gets text.
  caret(box('Write'), 5)
  await key(box('Write'), 'Enter')
  const draft = screen.getByLabelText<HTMLTextAreaElement>('New task')
  expect(document.activeElement).toBe(draft)
  expect(calls('POST task')).toHaveLength(1)
  // A line not stored yet does nothing but take text.
  await press(screen.getByRole('checkbox', { name: '' }))
  expect(calls('PATCH task')).toHaveLength(1)
  const gate = hold('POST task')
  await type(draft, 'Fix (2)')
  await blur(draft)
  expect(screen.getByLabelText('Edit Fix')).toBeTruthy()
  await gate.release()
  await settle()
  expect(calls('POST task').at(-1)!.body).toEqual({ title: 'Fix (2)', week: WEEK, slot: 'wed' })
  expect(row('Fix').dataset.taskId).toBe('task_4')
})

it('keeps the caret on a new line while it is stored, and leaves a cut line whole when only its end moved', async () => {
  task('Read')
  await open()
  caret(box('Read'), 0)
  await key(box('Read'), 'Enter')
  await settle()
  // Enter at the start keeps the text above: an emptied line keeps its words.
  expect(titles('day-wed')).toEqual(['Read', 'Read'])
  expect(calls('PATCH task')).toHaveLength(0)
  const second = screen.getAllByLabelText<HTMLTextAreaElement>('Edit Read')[1]
  caret(second, 4)
  await key(second, 'Enter')
  const draft = screen.getByLabelText<HTMLTextAreaElement>('New task')
  await type(draft, 'Go')
  const gate = hold('POST task')
  await blur(draft)
  // A line not stored yet splits and joins too.
  caret(box('Go'), 1)
  await key(box('Go'), 'Enter')
  expect(document.activeElement!.getAttribute('aria-label')).toBe('Edit o')
  await gate.release()
  await settle()
  expect(document.activeElement!.getAttribute('aria-label')).toBe('Edit o')
  expect(calls('PATCH task')).toHaveLength(0)
})

